export function getQuestionsByGradeAndTopic(
  gradeLevel: 'grade-2' | 'grade-3',
  topicId?: string
): ArenaQuestion[] {
  let list = ARENA_QUESTIONS_CATALOG.filter((q) => q.gradeLevel === gradeLevel);
  if (topicId && topicId !== 'all') {
    list = list.filter((q) => q.topicId === topicId);
  }
  return list;
}
