// Helper to look up an item by ID
export function getItemDef(id: string): InventoryItem | undefined {
  const item = MASTER_ITEMS_CATALOG.find((i) => i.id === id);
  return item ? { ...item } : undefined;
}

// Starter equipment loadout for a new adventurer
export function getStarterLoadout(): Record<string, InventoryItem> {
  const sword = getItemDef('wp-sword-apprentice');
  const shield = getItemDef('arm-shield-valour');
  const helmet = getItemDef('arm-helmet-scout');
  const armor = getItemDef('arm-armor-explorer');
  const amulet = getItemDef('acc-amulet-origin');

  const res: Record<string, InventoryItem> = {};
  if (sword) res.weapon = sword;
  if (shield) res.shield = shield;
  if (helmet) res.helmet = helmet;
  if (armor) res.armor = armor;
  if (amulet) res.amulet = amulet;
  return res;
}
