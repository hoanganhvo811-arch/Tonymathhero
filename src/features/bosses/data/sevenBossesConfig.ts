export const getBossConfig = (bossId: string, campaignId: CampaignId = 'grade-2'): BossData | undefined => {
  const catalog = campaignId === 'grade-3' ? GRADE_3_BOSSES : GRADE_2_BOSSES;
  return catalog[bossId] || GRADE_2_BOSSES[bossId];
};

export const getBossByKingdom = (kingdomId: string, campaignId: CampaignId = 'grade-2'): BossData | undefined => {
  const catalog = campaignId === 'grade-3' ? GRADE_3_BOSSES : GRADE_2_BOSSES;
  return Object.values(catalog).find((b) => b.kingdomId === kingdomId);
};
