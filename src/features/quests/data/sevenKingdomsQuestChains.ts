export const getQuestsForKingdom = (kingdomId: string, campaignId: CampaignId = 'grade-2'): Quest[] => {
  if (kingdomId === 'g2-k1-arithmia' || kingdomId === 'g3-k1-arithmia') {
    return EMERALD_FOREST_FULL_QUESTS.map((q) => ({
      ...q,
      campaignId,
      kingdomId,
    }));
  }

  const lookupKey = kingdomId.startsWith('g3-') ? kingdomId.replace('g3-', 'g2-') : kingdomId;
  const list = OTHER_KINGDOMS_QUESTS[lookupKey] || [];
  return list.map((q) => ({
    ...q,
    campaignId,
    kingdomId,
  }));
};
