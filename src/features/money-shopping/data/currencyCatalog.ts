export function getBillsByGrade(gradeLevel: 'grade-2' | 'grade-3'): CurrencyBill[] {
  if (gradeLevel === 'grade-2') {
    return VIETNAMESE_BILLS_CATALOG.filter((b) => b.gradeLevel === 'grade-2');
  }
  return VIETNAMESE_BILLS_CATALOG;
}

export function formatVnd(amount: number): string {
  return amount.toLocaleString('vi-VN') + ' đ';
}
